// 8b/10b codec exhaustive check + two link partners training to L0 over the PMA, data + SKP,
// error detection; 64b/66b and 128b/130b block lock, data integrity, lock loss and relock.
module tb_pcs;
  logic clk = 0, rst_n = 0;
  always #5 clk = ~clk;
  integer fails = 0, checks = 0;
  task automatic chk(input bit ok, input string what);
    checks++; if (!ok) begin fails++; $display("FAIL %s", what); end
  endtask

  // ---- 1. codec against the Python reference (all 268 symbols x 2 disparities) ----
  logic ek, erd, erd_o, kerr; logic [7:0] ed; logic [9:0] ecode;
  logic [7:0] dd; logic dk, drd_o, cerr, derr;
  enc8b10b u_e (.k(ek), .d(ed), .rd(erd), .code(ecode), .rd_out(erd_o), .k_err(kerr));
  dec8b10b u_d (.code(ecode), .rd(erd), .d(dd), .k(dk), .rd_out(drd_o), .code_err(cerr), .disp_err(derr));

  // ---- 2. 8b/10b link partners A <-> B ----
