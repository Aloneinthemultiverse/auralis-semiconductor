  logic [3:0] vk, vrd, vro; logic [7:0] vd; logic [11:0] vc;

  initial begin
    // 1. exhaustive codec vectors
    n = 0;
    for (int v = 0; v < NVEC; v++) begin
      {vk[0], vd, vrd[0], vc[9:0], vro[0]} = VEC[v*21 +: 21];
      ek = vk[0]; ed = vd; erd = vrd[0]; #1;
      chk(ecode === vc[9:0] && erd_o === vro[0] && !kerr, $sformatf("encode k=%0d d=%h rd=%0d", ek, ed, erd));
      chk(dd === ed && dk === ek && !cerr && !derr, $sformatf("decode k=%0d d=%h rd=%0d", ek, ed, erd));
      n++;
    end
    chk(n == 536, $sformatf("%0d codec vectors", n));
    force u_d.code = 10'b1111111111; #1; chk(u_d.code_err, "invalid word detected"); release u_d.code;

    // 2./3. links
    repeat (3) @(negedge clk); rst_n = 1;
    for (int c = 0; c < 4000 && !(a_st == 2 && b_st == 2); c++) @(negedge clk);
    chk(a_st == 2 && b_st == 2, "both 8b/10b partners trained to L0 (offsets 3 and 7 bits)");
    for (int c = 0; c < 800; c++) begin
      a_txv = 1; b_txv = 1; a_txd = $urandom; b_txd = $urandom;
      @(negedge clk);
    end
    a_txv = 0; b_txv = 0;
    repeat (30) @(negedge clk);
    chk(got_ab > 700 && got_ba > 700, $sformatf("data delivered across SKP insertion (%0d, %0d)", got_ab, got_ba));
    chk(a_err == 0 && b_err == 0, "no symbol errors on a clean channel");
    flip_ab = 1; @(negedge clk); flip_ab = 0; repeat (5) @(negedge clk);
    chk(b_err > 0, "injected bit error detected by the decoder");

    // block PCS: idle data until lock, then compare
    for (int c = 0; c < 400; c++) begin
      e_v = 1; e_c = (c % 50 == 0); e_d = {$urandom, $urandom};
      p_v = 1; p_c = (c % 50 == 0); p_d = {$urandom, $urandom, $urandom, $urandom};
      if (e_lk && !e_cmp) e_cmp = 1;
      if (p_lk && !p_cmp) p_cmp = 1;
      @(negedge clk);
    end
    chk(e_lk && e_sl > 0, $sformatf("64b/66b block lock found offset %0d after %0d slips", e_off, e_sl));
    chk(p_lk && p_sl > 0, $sformatf("128b/130b block lock found offset %0d after %0d slips", p_off, p_sl));
    chk(got_e > 250 && got_p > 200, $sformatf("blocks compared: %0d (66b) %0d (130b)", got_e, got_p));
    // burst of header errors drops lock, then relocks
    begin
      int saved;
      saved = fails;
      e_cmp = 0;
      for (int c = 0; c < 20; c++) begin e_flip = 1; @(negedge clk); end
      e_flip = 0;
      chk(!e_lk, "lock lost after >16 bad headers in 64");
      for (int c = 0; c < 300 && !e_lk; c++) begin e_d = {$urandom, $urandom}; @(negedge clk); end
      chk(e_lk, "relocked");
    end
    e_v = 0; p_v = 0;
    $display("%0d checks, %0d failures", checks, fails);
    if (fails == 0) $display("ALL TESTS PASSED"); else $display("TESTS FAILED");
    $finish;
  end
endmodule

// Behavioural PMA: serializer + channel + CDR-recovered deserializer, modelled at word rate.
// The channel delays the bit stream by OFFSET bits (unknown to the receiver) and flips bits on demand.
module pma_model #(parameter int W = 10) (
  input  logic         clk,
  input  logic [W-1:0] tx,
  input  int           offset,
  input  logic         flip,          // flip one bit of this word
  input  logic         kill,          // drop the word (all zeros: invalid header / code)
  output logic [W-1:0] rx
);
  logic [2*W-1:0] sr = '0;
  always @(posedge clk) sr <= {sr[W-1:0], tx};
  always_comb begin
    rx = sr[2*W-1 - offset -: W];
    if (flip) rx[W/2] = ~rx[W/2];
    if (kill) rx = '0;
  end
endmodule

