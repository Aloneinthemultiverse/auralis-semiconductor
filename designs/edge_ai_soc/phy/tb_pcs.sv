  logic [7:0] a_txd = 0, b_txd = 0, a_rxd, b_rxd;
  logic [9:0] a_code, b_code, a_raw, b_raw;
  logic [1:0] a_st, b_st;
  logic [15:0] a_err, b_err;
  int off_ab = 3, off_ba = 7;
  logic flip_ab = 0, flip_ba = 0;
  link8b10b #(.SKP_INT(40)) u_a (.clk(clk), .rst_n(rst_n), .tx_valid(a_txv), .tx_data(a_txd), .tx_ready(a_rdy),
    .rx_valid(a_rxv), .rx_data(a_rxd), .tx_code(a_code), .rx_raw(a_raw), .state(a_st), .err_count(a_err));
  link8b10b #(.SKP_INT(40)) u_b (.clk(clk), .rst_n(rst_n), .tx_valid(b_txv), .tx_data(b_txd), .tx_ready(b_rdy),
    .rx_valid(b_rxv), .rx_data(b_rxd), .tx_code(b_code), .rx_raw(b_raw), .state(b_st), .err_count(b_err));
  pma_model #(10) ch_ab (.clk(clk), .tx(a_code), .offset(off_ab), .flip(flip_ab), .kill(1'b0), .rx(b_raw));
  pma_model #(10) ch_ba (.clk(clk), .tx(b_code), .offset(off_ba), .flip(flip_ba), .kill(1'b0), .rx(a_raw));

  // ---- 3. block PCS: 64b/66b self-sync and 128b/130b additive ----
  logic e_v = 0, e_c = 0; logic [63:0] e_d = 0; logic [65:0] e_blk, e_raw; logic e_lk, e_rv, e_rc; logic [63:0] e_rd; logic [15:0] e_sl;
  int e_off = 23; logic e_flip = 0;
  blk_pcs_tx #(64, 0) e_tx (.clk(clk), .rst_n(rst_n), .valid(e_v), .ctrl(e_c), .data(e_d), .block(e_blk));
  pma_model #(66) e_ch (.clk(clk), .tx(e_blk), .offset(e_off), .flip(1'b0), .kill(e_flip), .rx(e_raw));
  blk_pcs_rx #(64, 0) e_rx (.clk(clk), .rst_n(rst_n), .raw(e_raw), .locked(e_lk), .valid(e_rv), .ctrl(e_rc), .data(e_rd), .slips(e_sl));
  logic p_v = 0, p_c = 0; logic [127:0] p_d = 0; logic [129:0] p_blk, p_raw; logic p_lk, p_rv, p_rc; logic [127:0] p_rd; logic [15:0] p_sl;
  int p_off = 77; logic p_flip = 0;
  blk_pcs_tx #(128, 1) p_tx (.clk(clk), .rst_n(rst_n), .valid(p_v), .ctrl(p_c), .data(p_d), .block(p_blk));
  pma_model #(130) p_ch (.clk(clk), .tx(p_blk), .offset(p_off), .flip(p_flip), .kill(1'b0), .rx(p_raw));
  blk_pcs_rx #(128, 1) p_rx (.clk(clk), .rst_n(rst_n), .raw(p_raw), .locked(p_lk), .valid(p_rv), .ctrl(p_rc), .data(p_rd), .slips(p_sl));

  // reference queues
  logic [7:0]   q_ab [$];
  logic [7:0]   q_ba [$];
  logic [64:0]  q_e  [$];
  logic [128:0] q_p  [$];
  logic e_cmp = 0, p_cmp = 0, p_sync = 0, e_synced = 0, p_synced = 0;
  int e_skip = 2;
  int got_ab = 0, got_ba = 0, got_e = 0, got_p = 0;

  always @(posedge clk) begin
    if (a_txv && a_rdy) q_ab.push_back(a_txd);
    if (b_txv && b_rdy) q_ba.push_back(b_txd);
    if (b_rxv && q_ab.size() > 0) begin got_ab++; chk(b_rxd === q_ab.pop_front(), "A->B byte"); end
    if (a_rxv && q_ba.size() > 0) begin got_ba++; chk(a_rxd === q_ba.pop_front(), "B->A byte"); end
    if (e_v) q_e.push_back({e_c, e_d});
    if (p_v) q_p.push_back({p_c, p_d});
    if (e_rv && e_cmp) begin
      if (e_skip > 0) e_skip--;                          // self-sync descrambler settling
      else if (!e_synced) begin                          // find the stream position once
        int k;
        logic [64:0] dummy;
        k = 0;
        while (k < q_e.size() && q_e[k] !== {e_rc, e_rd}) k++;
        if (k < q_e.size()) begin
          for (int j = 0; j <= k; j++) dummy = q_e.pop_front();
          e_synced = 1; got_e++;
        end
      end else begin
        logic [64:0] x;
        x = q_e.pop_front(); got_e++;
        chk({e_rc, e_rd} === x, "64b/66b block");
      end
    end
    if (p_rv && p_cmp) begin
      if (p_rc) p_sync = 1;                              // LFSR reseeded by an ordered set
      if (p_sync && !p_synced) begin
        int k;
        logic [128:0] dummy;
        k = 0;
        while (k < q_p.size() && q_p[k] !== {p_rc, p_rd}) k++;
        if (k < q_p.size()) begin
          for (int j = 0; j <= k; j++) dummy = q_p.pop_front();
          p_synced = 1; got_p++;
        end
      end else if (p_synced) begin
        logic [128:0] x;
        x = q_p.pop_front(); got_p++;
        chk({p_rc, p_rd} === x, "128b/130b block");
      end
    end
  end

