"""8b/10b (Widmer-Franaszek, IEEE 802.3 clause 36) reference + SystemVerilog table generator.
Checks the code properties before emitting RTL: DC balance (word disparity in {-2,0,2}), max run
length 5, running disparity bounded, comma K28.1/K28.5/K28.7 unique among valid sequences,
decode(encode(x)) == x for all 256 D and 12 K codes in both disparities."""
import itertools, re, sys

T6 = {  # EDCBA -> (RD- abcdei, RD+ abcdei)
    0: ("100111", "011000"), 1: ("011101", "100010"), 2: ("101101", "010010"), 3: ("110001",) * 2,
    4: ("110101", "001010"), 5: ("101001",) * 2, 6: ("011001",) * 2, 7: ("111000", "000111"),
    8: ("111001", "000110"), 9: ("100101",) * 2, 10: ("010101",) * 2, 11: ("110100",) * 2,
    12: ("001101",) * 2, 13: ("101100",) * 2, 14: ("011100",) * 2, 15: ("010111", "101000"),
    16: ("011011", "100100"), 17: ("100011",) * 2, 18: ("010011",) * 2, 19: ("110010",) * 2,
    20: ("001011",) * 2, 21: ("101010",) * 2, 22: ("011010",) * 2, 23: ("111010", "000101"),
    24: ("110011", "001100"), 25: ("100110",) * 2, 26: ("010110",) * 2, 27: ("110110", "001001"),
    28: ("001110",) * 2, 29: ("101110", "010001"), 30: ("011110", "100001"), 31: ("101011", "010100"),
}
K28_6 = ("001111", "110000")
T4D = {0: ("1011", "0100"), 1: ("1001",) * 2, 2: ("0101",) * 2, 3: ("1100", "0011"), 4: ("1101", "0010"),
       5: ("1010",) * 2, 6: ("0110",) * 2, 7: ("1110", "0001")}
A7 = ("0111", "1000")
T4K = {0: ("1011", "0100"), 1: ("0110", "1001"), 2: ("1010", "0101"), 3: ("1100", "0011"),
       4: ("1101", "0010"), 5: ("0101", "1010"), 6: ("1001", "0110"), 7: ("0111", "1000")}
KCODES = [(28, y) for y in range(8)] + [(23, 7), (27, 7), (29, 7), (30, 7)]

def disp(s): return s.count("1") - s.count("0")

def encode(byte, k, rd):
    """rd: -1 or +1. Returns (10-bit string abcdeifghj, new rd)."""
    x, y = byte & 31, byte >> 5
    if k:
        assert (x, y) in KCODES, (x, y)
        six = (K28_6 if x == 28 else T6[x])[0 if rd < 0 else 1]
    else:
        six = T6[x][0 if rd < 0 else 1]
    d6 = disp(six)
    rd1 = rd if d6 == 0 else (1 if d6 > 0 else -1)
    if k:
        four = T4K[y][0 if rd1 < 0 else 1]
    elif y == 7 and ((rd1 < 0 and x in (17, 18, 20)) or (rd1 > 0 and x in (11, 13, 14))):
        four = A7[0 if rd1 < 0 else 1]
    else:
        four = T4D[y][0 if rd1 < 0 else 1]
    d4 = disp(four)
    rd2 = rd1 if d4 == 0 else (1 if d4 > 0 else -1)
    return six + four, rd2

# ---- build tables and decode map ----
dec = {}
for k in (0, 1):
    for byte in range(256):
        if k and (byte & 31, byte >> 5) not in KCODES:
            continue
        for rd in (-1, 1):
            w, _ = encode(byte, k, rd)
            prev = dec.get(w)
            assert prev is None or prev == (byte, k), (w, prev, byte, k)
            dec[w] = (byte, k)

# ---- properties ----
for w in dec:
    assert disp(w) in (-2, 0, 2), w
import random
random.seed(1)
rd, stream = -1, ""
for _ in range(20000):
    k = random.random() < 0.1
    b = random.choice([28 | (y << 5) for y in range(7)] + [23 | 224, 27 | 224, 29 | 224, 30 | 224]) if k else random.randrange(256)  # K28.7 excluded: it can form misaligned commas (standard restriction)
    w, rd = encode(b, k, rd)
    stream += w
run = max(len(list(g)) for _, g in itertools.groupby(stream))
assert run <= 5, run
comma = ("0011111", "1100000")
occ = [m.start() for c in comma for m in re.finditer("(?=" + c + ")", stream)]
commas_ok = len(occ) > 0 and all(o % 10 == 0 for o in occ)
assert commas_ok, sorted(set(o % 10 for o in occ))
print(f"{len(occ)} commas all word-aligned (K28.7 restricted); {len(dec)} codewords, max run {run}, words balanced, decode unique, comma alignment ok={commas_ok}")

# ---- emit SystemVerilog ----
def sv_bits(s): return f"10'b{s}"
lines = ["// GENERATED by gen_8b10b.py (IEEE 802.3 cl.36 tables, property-checked). Do not edit.",
         "// enc8b10b: {abcdei,fghj} with a = bit 9 (first on the wire). rd: 0 = RD-, 1 = RD+.",
         "module enc8b10b (", "  input  logic       k,", "  input  logic [7:0] d,", "  input  logic       rd,",
         "  output logic [9:0] code,", "  output logic       rd_out,", "  output logic       k_err", ");",
         "  always_comb begin", "    k_err = 1'b0;", "    case ({k, rd, d})"]
for k in (0, 1):
    for rd in (-1, 1):
        for byte in range(256):
            if k and (byte & 31, byte >> 5) not in KCODES:
                continue
            w, rdn = encode(byte, k, rd)
            lines.append(f"      10'h{(k << 9) | ((rd > 0) << 8) | byte:03x}: begin code = {sv_bits(w)}; rd_out = 1'b{int(rdn > 0)}; end")
lines += ["      default: begin code = 10'b0; rd_out = rd; k_err = 1'b1; end", "    endcase", "  end", "endmodule", "",
          "// dec8b10b: code -> {k, d}; code_err for invalid words, disp_err when the word's disparity",
          "// contradicts the running disparity.",
          "module dec8b10b (", "  input  logic [9:0] code,", "  input  logic       rd,", "  output logic [7:0] d,",
          "  output logic       k,", "  output logic       rd_out,", "  output logic       code_err,",
          "  output logic       disp_err", ");",
          "  logic signed [4:0] dsp;", "  always_comb begin",
          "    dsp = 0;", "    for (int i = 0; i < 10; i++) dsp = dsp + (code[i] ? 5'sd1 : -5'sd1);",
          "    code_err = 1'b0;", "    case (code)"]
for w, (byte, k) in sorted(dec.items()):
    lines.append(f"      10'b{w}: begin d = 8'h{byte:02x}; k = 1'b{k}; end")
lines += ["      default: begin d = 8'h00; k = 1'b0; code_err = 1'b1; end", "    endcase",
          "    disp_err = (rd == 1'b0 && dsp < 0) || (rd == 1'b1 && dsp > 0);",
          "    rd_out   = (dsp > 0) ? 1'b1 : (dsp < 0) ? 1'b0 : rd;", "  end", "endmodule"]
open(sys.argv[1], "w").write("\n".join(lines) + "\n")

# vectors for the testbench: k d rd code rd_out
with open(sys.argv[2], "w") as f:
    for k in (0, 1):
        for rd in (-1, 1):
            for byte in range(256):
                if k and (byte & 31, byte >> 5) not in KCODES:
                    continue
                w, rdn = encode(byte, k, rd)
                f.write(f"{k:01x} {byte:02x} {int(rd > 0):01x} {int(w, 2):03x} {int(rdn > 0):01x}\n")
print("emitted")
